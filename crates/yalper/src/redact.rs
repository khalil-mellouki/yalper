    fn a_secret_only_after_the_cut_is_dropped() {
        let github = format!("ghp_{}", fake(ALNUM, 36, 25));
        let text = format!("{}{github}", "x".repeat(MAX_STRING_BYTES + 100));
        let result = redact_str(&text).unwrap();
        assert!(!result.contains("ghp_") && !result.contains("REDACTED"));
    }

    #[test]
    fn a_json_value_is_cut_to_its_budget() {
        let big = "z".repeat(MAX_STRING_BYTES);
        let mut value = json!({ "parts": [big, big, big, big, big, "short", ""] });
        redact_json(&mut value);
        let parts: Vec<&str> = value["parts"]
            .as_array()
            .unwrap()
            .iter()
            .map(|part| part.as_str().unwrap())
            .collect();
        let kept: usize = parts.iter().map(|part| part.matches('z').count()).sum();
        assert!(kept <= MAX_JSON_TEXT_BYTES, "{kept} bytes kept");
        assert_eq!(parts[0], big);
        assert!(parts[3].ends_with(&truncation_marker(MAX_STRING_BYTES)));
        assert_eq!(parts[4], truncation_marker(MAX_STRING_BYTES));
        assert_eq!(parts[5], truncation_marker(5));
        assert_eq!(parts[6], "");
    }

    #[test]
    fn tiny_strings_use_up_the_budget_too() {
        let count = MAX_JSON_TEXT_BYTES / STRING_COST_BYTES + 10;
        let mut value = Value::Array(vec![Value::from("ey"); count]);
        redact_json(&mut value);
        let items = value.as_array().unwrap();
        assert_eq!(items[0], "ey");
        assert_eq!(items[count - 1], truncation_marker(2));
    }

