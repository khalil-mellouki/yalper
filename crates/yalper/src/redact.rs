    /// redacted text.
    #[track_caller]
    fn assert_masked(text: &str, secret: &str, rule: &str) -> String {
        let result = redacted(text);
        assert!(!result.contains(secret), "secret left in {result:?}");
        assert!(
            result.contains(&format!("[REDACTED:{rule}]")),
            "no {rule} marker in {result:?}"
        );
        result
    }

