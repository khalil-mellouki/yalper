//! Secret redaction: masks API keys, tokens, passwords, and similar secrets in hook payloads before anything
//! is written to disk.
//!
//! The rules are gitleaks' (v8.30.1, MIT, see `third_party/gitleaks/`), turned into a static table by
//! `build.rs`. A hook runs in a new process every time, so compiling all 221 regexes up front (about 50 ms)
//! is not an option. Instead, one case-insensitive pass over the text finds which rule keywords occur, and
//! only the rules with a keyword hit are compiled (once per process) and run. Text with no keyword costs a
//! single substring scan.
//!
//! Each match's secret (the rule's secret group, else the first non-empty group, else the whole match) is
//! kept when its Shannon entropy is at or above the rule's threshold, and replaced with
//! `[REDACTED:<rule-id>]`. gitleaks' allowlists and stopwords are not applied: masking a harmless value is
//! better than writing a real secret to disk.

use std::cmp::Reverse;
use std::fmt::Write as _;
use std::sync::OnceLock;

use aho_corasick::AhoCorasick;
use regex_automata::meta::{self, Regex};
use regex_automata::util::syntax;
use serde_json::Value;

/// Longer strings are cut to this many bytes and end with `[TRUNCATED: <original length> bytes in total]`.
pub const MAX_STRING_BYTES: usize = 256 * 1024;

/// The most text one [`redact_json`] call scans. Running every rule costs about 200 ns per byte, and
/// hostile text (a file the agent reads, a command's output) can contain every keyword, so without this
/// bound a 64 MiB payload could hold up the agent for many seconds; with it, the worst case measured on a
/// Windows laptop is about 0.4 s. Once it is used up, every further string is replaced by its truncation
/// marker. Real payloads stay far below it.
pub const MAX_JSON_TEXT_BYTES: usize = 1024 * 1024;

/// What each string costs from [`MAX_JSON_TEXT_BYTES`] on top of its length: the fixed work of scanning
/// one string, so that a payload of millions of tiny strings is bounded too.
const STRING_COST_BYTES: usize = 64;

/// How far past the cut a long string is still scanned, so a secret that straddles the cut is masked
/// instead of leaving its first bytes behind. Larger than any realistic secret, including a PEM private
/// key block.
const CUT_OVERLAP_BYTES: usize = 16 * 1024;

/// One gitleaks rule, as generated by `build.rs`.
struct Rule {
    id: &'static str,
    regex: &'static str,
    /// The capture group holding the secret, or 0 to use the first non-empty group (or the whole match).
    secret_group: usize,
    /// Minimum Shannon entropy of the secret, in bits per byte; 0 means no check.
    entropy: f64,
}

// Defines `RULE_COUNT`, `RULES`, `KEYWORDS` (lowercase, sorted) and `KEYWORD_RULES` (for each keyword,
// the indexes of the rules that list it).
include!(concat!(env!("OUT_DIR"), "/gitleaks_rules.rs"));

/// Redacts every string in `value`, object keys included, in place, in document order. Each string is cut to
/// [`MAX_STRING_BYTES`] and the whole value to [`MAX_JSON_TEXT_BYTES`] first.
pub fn redact_json(value: &mut Value) {
    let mut budget = MAX_JSON_TEXT_BYTES;
    redact_value(value, &mut budget);
}

/// `text` with its secrets masked and cut to [`MAX_STRING_BYTES`], or `None` when it is unchanged.
pub fn redact_str(text: &str) -> Option<String> {
    redact_cut(text, MAX_STRING_BYTES)
}

/// Appended to a string that was cut, with the original length so the record shows how much was dropped.
fn truncation_marker(original_bytes: usize) -> String {
    format!("[TRUNCATED: {original_bytes} bytes in total]")
}

fn redact_value(value: &mut Value, budget: &mut usize) {
    match value {
        Value::String(text) => {
            if let Some(redacted) = redact_charged(text, budget) {
                *text = redacted;
            }
        }
        Value::Array(items) => items.iter_mut().for_each(|item| redact_value(item, budget)),
        Value::Object(map) => {
            // Keys are rebuilt in their original order. If two keys become equal after redaction (or after
            // the budget ran out), the later entry replaces the earlier one.
            for (key, mut item) in std::mem::take(map) {
                let key = redact_charged(&key, budget).unwrap_or(key);
                redact_value(&mut item, budget);
                map.insert(key, item);
            }
        }
        Value::Null | Value::Bool(_) | Value::Number(_) => {}
    }
}

/// Redacts one string of a JSON value, cut to what is left of `budget`, and charges the budget.
fn redact_charged(text: &str, budget: &mut usize) -> Option<String> {
    let limit = (*budget).min(MAX_STRING_BYTES);
    *budget = budget.saturating_sub(text.len().min(limit) + STRING_COST_BYTES);
    redact_cut(text, limit)
}

/// `text` cut to at most `limit` bytes, with its secrets masked, or `None` when it is unchanged.
fn redact_cut(text: &str, limit: usize) -> Option<String> {
    let keep_end = floor_char_boundary(text, limit);
    let scan_end = if keep_end == 0 {
        0
    } else {
        floor_char_boundary(text, limit + CUT_OVERLAP_BYTES)
    };
    let secrets = find_secrets(&text[..scan_end]);
    if secrets.is_empty() && keep_end == text.len() {
        return None;
    }

    let mut redacted = String::with_capacity(keep_end + 64);
    let mut position = 0;
    for secret in secrets.iter().take_while(|secret| secret.start < keep_end) {
        redacted.push_str(&text[position..secret.start]);
        write!(redacted, "[REDACTED:{}]", RULES[secret.rule].id).unwrap();
        position = secret.end;
    }
    if position < keep_end {
        redacted.push_str(&text[position..keep_end]);
    }
    if keep_end < text.len() {
        redacted.push_str(&truncation_marker(text.len()));
    }
    Some(redacted)
}

/// A byte range of the text to mask, and the rule that found it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Secret {
    start: usize,
    end: usize,
    rule: usize,
}

/// The secrets in `text`, sorted and merged so that no two ranges overlap, on character boundaries.
fn find_secrets(text: &str) -> Vec<Secret> {
    let mut candidates = [false; RULE_COUNT];
    let mut any = false;
    for hit in keyword_finder().find_overlapping_iter(text) {
        for &rule in KEYWORD_RULES[hit.pattern().as_usize()] {
            candidates[usize::from(rule)] = true;
            any = true;
        }
    }
    if !any {
        return Vec::new();
    }

    let bytes = text.as_bytes();
    let mut secrets = Vec::new();
    for (index, rule) in RULES.iter().enumerate() {
        if !candidates[index] {
            continue;
        }
        let Some(regex) = compiled(index) else {
            continue;
        };
        for captures in regex.captures_iter(bytes) {
            let secret = if rule.secret_group > 0 {
                captures.get_group(rule.secret_group)
            } else {
                (1..captures.group_len())
                    .filter_map(|group| captures.get_group(group))
                    .find(|group| !group.is_empty())
                    .or_else(|| captures.get_group(0))
            };
            let Some(secret) = secret.filter(|secret| !secret.is_empty()) else {
                continue;
            };
            // gitleaks drops a match at or below the threshold; keeping the equal case masks slightly more.
            if rule.entropy > 0.0 && shannon_entropy(&bytes[secret.range()]) < rule.entropy {
                continue;
            }
            secrets.push(Secret {
                start: floor_char_boundary(text, secret.start),
                end: ceil_char_boundary(text, secret.end),
                rule: index,
            });
        }
    }

    secrets.sort_unstable_by_key(|secret| (secret.start, Reverse(secret.end), secret.rule));
    let mut merged: Vec<Secret> = Vec::with_capacity(secrets.len());
    for secret in secrets {
        match merged.last_mut() {
            Some(last) if secret.start < last.end => last.end = last.end.max(secret.end),
            _ => merged.push(secret),
        }
    }
    merged
}

/// The automaton over all rule keywords, built on first use.
fn keyword_finder() -> &'static AhoCorasick {
    static FINDER: OnceLock<AhoCorasick> = OnceLock::new();
    FINDER.get_or_init(|| {
        AhoCorasick::builder()
            .ascii_case_insensitive(true)
            .build(KEYWORDS)
            .expect("the rule keywords form a valid automaton")
    })
}

/// Rule `index`'s regex, compiled on first use. `None` if it does not compile (a test checks they all do).
fn compiled(index: usize) -> Option<&'static Regex> {
    static COMPILED: [OnceLock<Option<Regex>>; RULE_COUNT] =
        [const { OnceLock::new() }; RULE_COUNT];
    COMPILED[index]
        .get_or_init(|| build_regex(RULES[index].regex).ok())
        .as_ref()
}

/// Compiles a gitleaks regex with the engine behind the `regex` crate, configured like `regex::bytes`.
///
/// Go's RE2, which gitleaks uses, treats `\w`, `\s`, `\b` and `(?i)` as ASCII, so Unicode mode is off:
/// that is both the faithful port and about 90 times faster to compile. The one-pass DFA is off, since
/// captures only run on the span of a match. The literal prefilter is off for the 101 rules built from
/// gitleaks' semi-generic template (`[\w.-]{0,50}?` before a keyword, as in `generic-api-key`, which
/// nearly every payload triggers): it more than doubles their compile time and does not speed up their
/// search (measured). For the other rules it is cheap and makes the search much faster.
fn build_regex(pattern: &str) -> Result<Regex, Box<meta::BuildError>> {
    let semi_generic = pattern.contains(r"[\w.-]{0,50}?");
    meta::Builder::new()
        .configure(
            meta::Config::new()
                .utf8_empty(false)
                .onepass(false)
                .auto_prefilter(!semi_generic),
        )
        .syntax(syntax::Config::new().unicode(false).utf8(false))
        .build(pattern)
        .map_err(Box::new)
}

/// Shannon entropy in bits per byte. gitleaks counts characters instead; secrets are ASCII, where both agree.
fn shannon_entropy(bytes: &[u8]) -> f64 {
    let mut counts = [0u32; 256];
    for &byte in bytes {
        counts[usize::from(byte)] += 1;
    }
    let length = bytes.len() as f64;
    counts
        .iter()
        .filter(|&&count| count > 0)
        .map(|&count| {
            let frequency = f64::from(count) / length;
            -frequency * frequency.log2()
        })
        .sum()
}

fn floor_char_boundary(text: &str, mut index: usize) -> usize {
    if index >= text.len() {
        return text.len();
    }
    while !text.is_char_boundary(index) {
        index -= 1;
    }
    index
}

fn ceil_char_boundary(text: &str, mut index: usize) -> usize {
    while !text.is_char_boundary(index) {
        index += 1;
    }
    index
}

