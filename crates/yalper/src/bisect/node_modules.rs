    #[test]
    fn node_loads_the_projects_packages_and_the_steps_workspace_package() {
        if !node() {
            return;
        }
        let project = Project::with_packages();
        let root_package = "{\"name\": \"root\", \"private\": true}\n";
        let lib_package = "{\"name\": \"@me/lib\", \"main\": \"index.js\"}\n";
        project.write("package.json", root_package);
        // `dep` needs `sub`, hoisted next to it, as npm installs them.
        project.write(
            "node_modules/dep/index.js",
            "module.exports = 'project dep, ' + require('sub');\n",
        );
        project.write("node_modules/sub/index.js", "module.exports = 'sub';\n");
        // `dep2` needs `sibling`, which pnpm puts only next to it in its store.
        let store = "node_modules/.pnpm/dep2@1.0.0/node_modules";
        project.write(
            &format!("{store}/dep2/index.js"),
            "module.exports = 'dep2, ' + require('sibling');\n",
        );
        project.write(
            &format!("{store}/sibling/index.js"),
            "module.exports = 'sibling';\n",
        );
        project.link_package("dep2", &format!("{store}/dep2"));
        project.write("packages/lib/package.json", lib_package);
        project.write("packages/lib/index.js", "module.exports = 'project lib';\n");
        project.link_package("@me/lib", "packages/lib");
        let before = state(project.path());

        let step = [
            (".gitignore", "node_modules/\n"),
            ("package.json", root_package),
            ("packages/lib/index.js", "module.exports = 'step lib';\n"),
            ("packages/lib/package.json", lib_package),
        ];
        let mut copy = project.copy();
        copy.switch(&project.store, project.tree(&step)).unwrap();
        project.node_modules().link(&mut copy).unwrap();

        let script = "const fs = require('fs');
            let sibling;
            try { require('sibling'); sibling = 'found'; } catch (error) { sibling = error.code; }
            const loaded = [require('dep'), require('dep2'), require('@me/lib'), sibling,
                require.resolve('dep')];
            fs.mkdirSync('node_modules/.vite', { recursive: true });
            fs.writeFileSync('node_modules/.vite/x', 'written by the test');
            process.stdout.write(JSON.stringify(loaded));";
        let output = Command::new("node")
            .args(["-e", script])
            .current_dir(copy.path())
            .output()
            .unwrap();
        assert!(output.status.success(), "{output:?}");
        let loaded: Vec<String> = serde_json::from_slice(&output.stdout).unwrap();
        assert_eq!(
            loaded[..4],
            [
                "project dep, sub",
                "dep2, sibling",
                "step lib",
                "MODULE_NOT_FOUND"
            ]
        );
        // Node resolved the link to the project's package.
        assert_eq!(
            fs::canonicalize(&loaded[4]).unwrap(),
            fs::canonicalize(project.path().join("node_modules/dep/index.js")).unwrap()
        );
        // The cache write landed in the copy.
        let vite = copy.path().join("node_modules/.vite");
        assert!(fs::symlink_metadata(&vite).unwrap().is_dir());
        assert_eq!(fs::read(vite.join("x")).unwrap(), b"written by the test");
        assert_eq!(state(project.path()), before);
    }
