//! Reuse of the project's installed Node packages in a test copy, without letting tests change them.
//!
//! For each folder of the step where the project has an installed `node_modules`, the copy gets a real
//! `node_modules` folder holding one link per package of the project's (a "link farm"): symlinks on Unix,
//! junctions on Windows, which need no privilege there. Node resolves a linked package to its real path, so
//! the package's own dependencies are found in the project's `node_modules` as usual (also in the stores of
//! pnpm, Bun and Deno). What a test creates at the top of the copy's `node_modules`, such as a `.vite` cache
//! or TypeScript's `.tmp`, stays in the copy. Known limit: a write inside one package's own folder still
//! reaches the project.
//!
//! The rules:
//!
//! - a `node_modules` folder is reused only if it is a real folder reached through real folders, the project's
//!   ignore rules ignore it, and the step's tree has nothing at its path (compared without regard to case,
//!   on every system);
//! - only packages are linked: entries whose name does not start with a dot, scope folders (`@me`), and the
//!   package manager folders of [`LINKED_DOT_FOLDERS`]. Every other dot folder is left for the copy to create.
//!   The files of [`COPIED_FILES`] are copied;
//! - a package that is a link into the project outside any `node_modules` (a workspace package, such as
//!   `node_modules/@me/lib -> ../../packages/lib`) is linked to the same folder inside the copy instead, so
//!   tests import the step's code, not the project's current code. A scope folder is linked whole, unless it
//!   holds such a package: it is then a real folder of links. A link that leads out of the project is never
//!   followed (see [`NodeModules::resolve`]);
//! - every farm is an extra path of the copy (see [`TestCopy::set_extra_paths`]), so switches keep it, and it
//!   is checked before every run: an entry that is not what Yalper made (a link a test changed, a file in
//!   place of a link, a link in place of the farm) is removed and made anew, never compared or written
//!   through. Other links a test put in a farm are removed; files and folders it created there are kept, like
//!   ignored build outputs;
//! - every farm is removed when the bisect ends ([`NodeModules::unlink`]), so that no link into the project
//!   stays in the cache folder between bisects; farms a bisect that ended abnormally left are removed by the
//!   first [`link`](NodeModules::link) of the next bisect that uses the copy;
//! - removing a farm never follows a link: `std::fs::remove_dir_all` removes links themselves, not what they
//!   point to, and so does deleting a whole copy.

use std::collections::{HashMap, HashSet};
use std::ffi::{OsStr, OsString};
use std::fs;
use std::io;
use std::path::{Component, Path, PathBuf};

use super::TestCopy;
use super::copy::{
    is_written_as, join, make_owner_writable, native, parents, remove_entry, write_file,
};
use super::link::{
    CANNOT_LINK, at, has_special_prefix, is_network, is_real_dir_no_follow, is_under, link_to,
    list, plain,
};
use crate::safe_fs;
use crate::snapshot::{CASE_INSENSITIVE, Excludes, FileKind};

const NODE_MODULES: &str = "node_modules";

/// The folders at the top of `node_modules` whose name starts with a dot that are linked: the packages'
/// commands, and the stores of pnpm, Bun (isolated installs) and Deno, which the package links point into.
/// Every other dot folder is left for the copy to create, because tools write there (`.vite`, `.cache`,
/// TypeScript's `.tmp`, `.astro`): a link would send those writes into the project.
const LINKED_DOT_FOLDERS: [&str; 4] = [".bin", ".bun", ".deno", ".pnpm"];

/// The files at the top of `node_modules` that package managers read to tell what is installed (npm, pnpm,
/// Yarn 1, Yarn 2 and later). They are copied, if regular files of at most [`MAX_COPIED_FILE_BYTES`].
const COPIED_FILES: [&str; 4] = [
    ".modules.yaml",
    ".package-lock.json",
    ".yarn-integrity",
    ".yarn-state.yml",
];

const MAX_COPIED_FILE_BYTES: u64 = 1024 * 1024;

/// The link farms of one test copy (the copy that reuses the project's installed dependencies).
pub struct NodeModules {
    /// The project folder, absolute: the links point into it.
    project: PathBuf,
    /// The project folder with every link resolved, to tell where a link of `node_modules` leads.
    project_real: PathBuf,
    /// Whether the project is on a network drive (see [`CANNOT_LINK`]).
    on_network: bool,
    excludes: Excludes,
    /// Folders of the project whose `.gitignore` was read into `excludes`.
    rules_read: HashSet<String>,
    /// What the farm of each folder holds, by folder (relative, `/`-separated, `""` for the root): `None` if
    /// the project has no `node_modules` there that can be reused. Read once, since the project's packages do
    /// not change during a bisect.
    found: HashMap<String, Option<Vec<(OsString, Want)>>>,
    /// The `node_modules` folders of the copy that are farms, relative and `/`-separated.
    farms: HashSet<String>,
    /// Whether the copy was checked for farms an earlier bisect left in folders that no longer get one.
    checked: bool,
    /// Whether a link was made in the copy (see [`link_to`]).
    made_link: bool,
    /// Whether each folder of the project (relative, `/`-separated) and every folder above it are real
    /// folders, not links (see [`is_real_in_project`](Self::is_real_in_project)).
    real_dirs: HashMap<String, bool>,
}

/// What an entry of a farm must be.
enum Want {
    /// A link to this folder of the project.
    Link(PathBuf),
    /// A link to this folder of the copy, relative to its root (a workspace package). Made only if the step
    /// has the folder.
    Workspace(PathBuf),
    /// A copy of this small file.
    File(Vec<u8>),
    /// A real folder holding these entries: a scope folder that holds a workspace package.
    Dir(Vec<(OsString, Want)>),
}

/// What a [`NodeModules::link`] did.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct Linked {
    /// Farms in the copy after the call.
    pub farms: usize,
    /// Links created, new or in place of a wrong entry.
    pub links: usize,
    /// Files copied, new or in place of a wrong entry.
    pub files: usize,
    /// Entries removed without a replacement: farms no longer wanted, a farm folder that was not a real
    /// folder, links a test put in a farm, workspace links whose package the step does not have.
    pub removed: usize,
}

impl NodeModules {
    /// The farms of a copy of the project at `project`. Use one value per copy, for one bisect.
    pub fn new(project: &Path) -> io::Result<Self> {
        // On Windows, a mapped network drive resolves to its share.
        let real = fs::canonicalize(project)?;
        let project = plain(&std::path::absolute(project)?);
        Ok(Self {
            excludes: Excludes::new(&project),
            project,
            on_network: is_network(&real),
            project_real: plain(&real),
            rules_read: HashSet::new(),
            found: HashMap::new(),
            farms: HashSet::new(),
            checked: false,
            made_link: false,
            real_dirs: HashMap::new(),
        })
    }

    /// Makes the copy's farms match the step it holds: called after every [`TestCopy::switch`], before the
    /// test run. Each folder of the step's tree where the project has a reusable `node_modules` gets a farm,
    /// checked and repaired entry by entry; farms of folders that no longer get one are removed, and the first
    /// call also removes those an earlier bisect left anywhere in the copy. The farms are registered as extra
    /// paths of the copy, next to the extra paths set by others.
    ///
    /// Fails with [`CANNOT_LINK`] if a farm is needed but links to the project cannot be made on this system:
    /// for a project on a network drive before changing anything, otherwise when the first link of a farm
    /// fails.
    pub fn link(&mut self, copy: &mut TestCopy) -> io::Result<Linked> {
        let (dirs, taken) = tree_dirs(copy)?;
        for dir in &dirs {
            self.find(dir)?;
        }
        let wanted: Vec<(&str, String)> = dirs
            .iter()
            .map(|dir| (dir.as_str(), join(dir, NODE_MODULES)))
            .filter(|(dir, farm)| {
                !taken.contains(&key(farm)) && self.found.get(*dir).is_some_and(Option::is_some)
            })
            .collect();
        if self.on_network && !wanted.is_empty() {
            return Err(io::Error::new(
                CANNOT_LINK,
                "the project is on a network drive, and Windows junctions can only point to local \
                 folders",
            ));
        }
        let wanted_farms: HashSet<String> = wanted.iter().map(|(_, farm)| farm.clone()).collect();

        let root = plain(&std::path::absolute(copy.path())?);
        let mut linked = Linked::default();
        let mut stale: Vec<String> = self.farms.difference(&wanted_farms).cloned().collect();
        if !self.checked {
            stale.extend(self.left_farms(&root, &wanted_farms, &taken)?);
        }
        let tree_dirs: HashSet<&str> = dirs.iter().map(String::as_str).collect();
        for farm in stale {
            // Where the tree now has files, the folder is the tree's: the switch already cleaned it.
            if !taken.contains(&key(&farm)) && remove_farm(&root, &farm, &tree_dirs)? {
                linked.removed += 1;
            }
        }
        self.checked = true;

        // Registered before the farms are made, so a farm left half made by an error is still known to the
        // next call, which completes it or removes it.
        let mut extra = copy.extra_paths().clone();
        extra.retain(|path| !self.farms.contains(path));
        extra.extend(wanted_farms.iter().cloned());
        copy.set_extra_paths(extra);
        self.farms = wanted_farms;

        for (dir, farm) in &wanted {
            // The switch made every folder of the tree a real folder; checked again, so nothing is ever
            // written through a link.
            for parent in parents(farm) {
                if !is_real_dir_no_follow(&native(&root, parent)) {
                    return Err(io::Error::other(format!(
                        "cannot link {farm} in the test copy: {parent} is not a real folder"
                    )));
                }
            }
            let Some(Some(wants)) = self.found.get(*dir) else {
                continue;
            };
            sync(
                &root,
                &native(&root, farm),
                wants,
                &mut linked,
                &mut self.made_link,
            )
            .map_err(|error| {
                io::Error::new(
                    error.kind(),
                    format!("cannot link {farm} in the test copy: {error}"),
                )
            })?;
        }
        linked.farms = wanted.len();
        Ok(linked)
    }

    /// Removes every farm of the copy, with what runs created in it, never following a link, and takes them
    /// out of the copy's extra paths: called when the bisect ends, so that no link into the project stays in the
    /// cache folder between bisects. The next [`link`](Self::link) makes them again. A farm that cannot be
    /// removed stays registered, and the first error is returned.
    pub fn unlink(&mut self, copy: &mut TestCopy) -> io::Result<()> {
        let root = plain(&std::path::absolute(copy.path())?);
        let farms = std::mem::take(&mut self.farms);
        // Farms are only made in folders of the tree: none of the folders above them is removed.
        let above: HashSet<&str> = farms.iter().flat_map(|farm| parents(farm)).collect();
        let mut failed = None;
        for farm in &farms {
            if let Err(error) = remove_farm(&root, farm, &above) {
                failed.get_or_insert(io::Error::new(
                    error.kind(),
                    format!("cannot remove {farm}: {error}"),
                ));
                self.farms.insert(farm.clone());
            }
        }
        let mut extra = copy.extra_paths().clone();
        extra.retain(|path| !farms.contains(path) || self.farms.contains(path));
        copy.set_extra_paths(extra);
        failed.map_or(Ok(()), Err)
    }

    /// The farms in the copy, relative and `/`-separated.
    pub(super) fn farms(&self) -> impl Iterator<Item = &str> {
        self.farms.iter().map(String::as_str)
    }

    /// Whether the project has a `node_modules` in its folder `dir` (relative, `/`-separated, `""` for the top)
    /// that [`link`](Self::link) would link: a real folder reached through real folders, and ignored.
    pub(super) fn reusable(&mut self, dir: &str) -> io::Result<bool> {
        self.find(dir)?;
        Ok(self.found.get(dir).is_some_and(Option::is_some))
    }

    /// Reads, once, what the farm of the folder `dir` of the project holds (see [`found`](Self::found)).
    fn find(&mut self, dir: &str) -> io::Result<()> {
        if self.found.contains_key(dir) {
            return Ok(());
        }
        let folder = join(dir, NODE_MODULES);
        let full = at(&self.project, &folder);
        let found = match fs::symlink_metadata(&full) {
            Ok(metadata) if metadata.is_dir() => {
                let in_real_dirs = parents(&folder)
                    .all(|parent| is_real_dir_no_follow(&at(&self.project, parent)));
                if in_real_dirs && self.is_ignored(&folder) {
                    Some(self.entries(&full, true)?)
                } else {
                    None
                }
            }
            Ok(_) => None,
            Err(error) if error.kind() == io::ErrorKind::NotFound => None,
            Err(error) => return Err(error),
        };
        self.found.insert(dir.to_owned(), found);
        Ok(())
    }

    /// Whether the project's ignore rules ignore the folder `folder` (relative, `/`-separated). If the rules
    /// go over the budget of a snapshot, nothing is taken as ignored.
    fn is_ignored(&mut self, folder: &str) -> bool {
        // The rules of every folder above it, outermost first, as a walk of the project reads them.
        for dir in std::iter::once("").chain(parents(folder)) {
            if self.rules_read.insert(dir.to_owned()) {
                self.excludes.add_dir(&at(&self.project, dir), true);
            }
        }
        !self.excludes.exceeded() && self.excludes.is_ignored(&at(&self.project, folder), true)
    }

    /// What the farm of the project's folder `dir` (a `node_modules` folder if `top`, else a scope folder in
    /// one) holds, sorted by name.
    fn entries(&self, dir: &Path, top: bool) -> io::Result<Vec<(OsString, Want)>> {
        let mut wants = Vec::new();
        for entry in fs::read_dir(dir)? {
            let entry = entry?;
            let (name, file_type, path) = (entry.file_name(), entry.file_type()?, entry.path());
            if top && name.as_encoded_bytes().starts_with(b".") {
                if file_type.is_file() && is_one_of(&name, &COPIED_FILES) {
                    if let Some(bytes) =
                        safe_fs::read_small_regular_file(&path, MAX_COPIED_FILE_BYTES)
                    {
                        wants.push((name, Want::File(bytes)));
                    }
                    continue;
                }
                if !is_one_of(&name, &LINKED_DOT_FOLDERS) {
                    continue;
                }
            }
            let want = if file_type.is_symlink() {
                match self.linked(&path) {
                    Some(want) => want,
                    None => continue,
                }
            } else if file_type.is_dir() {
                if top && name.as_encoded_bytes().starts_with(b"@") {
                    let scope = self.entries(&path, false)?;
                    if scope
                        .iter()
                        .any(|(_, want)| matches!(want, Want::Workspace(_)))
                    {
                        Want::Dir(scope)
                    } else {
                        Want::Link(path)
                    }
                } else {
                    Want::Link(path)
                }
            } else {
                continue;
            };
            wants.push((name, want));
        }
        wants.sort_unstable_by(|a, b| a.0.cmp(&b.0));
        Ok(wants)
    }

    /// What the farm holds for `link`, a link of the project's `node_modules`, or `None` to leave it out (see
    /// [`resolve`](Self::resolve)): a workspace package is linked to the copy's own folder, anything else
    /// (a package of a store such as `.pnpm`, a link that leads out of the project) to the project's entry.
    fn linked(&self, link: &Path) -> Option<Want> {
        match self.resolve(link) {
            Resolved::LeftOut => None,
            Resolved::Outside => Some(Want::Link(link.to_owned())),
            Resolved::Inside { relative, is_dir } => {
                if !is_dir {
                    return None;
                }
                let outside_node_modules = relative.components().all(|component| match component {
                    Component::Normal(name) => !name.to_str().is_some_and(is_node_modules),
                    _ => false,
                });
                Some(
                    if outside_node_modules && relative.components().next().is_some() {
                        Want::Workspace(relative)
                    } else {
                        Want::Link(link.to_owned())
                    },
                )
            }
        }
    }

    /// Where the link `link` leads, found one path component at a time from the project's folder, never
    /// following a link that leads out of the project: following it could reach a network share (and send
    /// the user's credentials) or start an automount. Each link met on the way is read with `read_link`
    /// and its target checked the same way, up to [`MAX_HOPS`] links.
    fn resolve(&self, link: &Path) -> Resolved {
        let (Some(parent), Ok(target)) = (link.parent(), fs::read_link(link)) else {
            return Resolved::LeftOut;
        };
        let mut path = parent.join(target);
        let mut hops = 0;
        'path: loop {
            if has_special_prefix(&path) {
                return Resolved::LeftOut;
            }
            let root = if is_under(&path, &self.project) {
                &self.project
            } else if is_under(&path, &self.project_real) {
                &self.project_real
            } else {
                return Resolved::Outside;
            };
            let rest: Vec<Component> = path.components().skip(root.components().count()).collect();
            let mut current = root.clone();
            let mut depth = 0;
            let mut is_dir = true;
            for (index, component) in rest.iter().enumerate() {
                match component {
                    Component::CurDir => {}
                    // Out of the project's folder.
                    Component::ParentDir if depth == 0 => return Resolved::Outside,
                    Component::ParentDir => {
                        current.pop();
                        depth -= 1;
                    }
                    Component::Normal(name) => {
                        current.push(name);
                        depth += 1;
                        let Ok(metadata) = fs::symlink_metadata(&current) else {
                            return Resolved::LeftOut;
                        };
                        if metadata.is_symlink() {
                            hops += 1;
                            let (Some(parent), Ok(target), true) =
                                (current.parent(), fs::read_link(&current), hops <= MAX_HOPS)
                            else {
                                return Resolved::LeftOut;
                            };
                            let mut next = parent.join(target);
                            next.extend(&rest[index + 1..]);
                            path = next;
                            continue 'path;
                        }
                        is_dir = metadata.is_dir();
                    }
                    Component::RootDir | Component::Prefix(_) => return Resolved::LeftOut,
                }
            }
            // No link on the way: `current` is a real path inside the project.
            let relative = current
                .strip_prefix(root)
                .map(Path::to_owned)
                .unwrap_or_default();
            return Resolved::Inside { relative, is_dir };
        }
    }

    /// The `node_modules` folders of the copy at `root` that are neither in `keep` nor the tree's (`taken`)
    /// and that hold a link, at their top or in a scope folder: farms an earlier bisect left. Links,
    /// `node_modules` folders, and folders the project's ignore rules ignore (build outputs such as `target/`,
    /// which can be large) are not entered: farms are only made in folders of a tree, which are not ignored.
    /// A folder that cannot be read, or is gone, is skipped.
    fn left_farms(
        &mut self,
        root: &Path,
        keep: &HashSet<String>,
        taken: &HashSet<String>,
    ) -> io::Result<Vec<String>> {
        let mut left = Vec::new();
        let mut todo = vec![String::new()];
        while let Some(dir) = todo.pop() {
            for (name, file_type, full) in list(&at(root, &dir))? {
                // The type of the entry itself: a link is not a folder here.
                if !file_type.is_dir() {
                    continue;
                }
                // Folders of a tree have UTF-8 names.
                let Some(name) = name.to_str() else {
                    continue;
                };
                let path = join(&dir, name);
                if is_node_modules(name) {
                    if !keep.contains(&path) && !taken.contains(&key(&path)) && holds_link(&full)? {
                        left.push(path);
                    }
                } else if !(self.is_real_in_project(&dir) && self.is_ignored(&path)) {
                    todo.push(path);
                }
            }
        }
        Ok(left)
    }

    /// Whether the project's folder `dir` (relative, `/`-separated, `""` for the root) and every folder
    /// above it are real folders, not links. The project's ignore rules for a folder of the copy are read
    /// only then: reading a `.gitignore` through a link of the project could reach a network share.
    fn is_real_in_project(&mut self, dir: &str) -> bool {
        if dir.is_empty() {
            return true;
        }
        if let Some(&real) = self.real_dirs.get(dir) {
            return real;
        }
        let parent = dir.rsplit_once('/').map_or("", |(parent, _)| parent);
        let real =
            self.is_real_in_project(parent) && is_real_dir_no_follow(&at(&self.project, dir));
        self.real_dirs.insert(dir.to_owned(), real);
        real
    }
}

/// Whether the folder `dir` holds a link at its top or in a scope folder (`@x`) at its top. Folders that
/// cannot be read are taken as holding none.
fn holds_link(dir: &Path) -> io::Result<bool> {
    for (name, file_type, full) in list(dir)? {
        if file_type.is_symlink() {
            return Ok(true);
        }
        if file_type.is_dir() && name.as_encoded_bytes().starts_with(b"@") {
            for (_, inner, _) in list(&full)? {
                if inner.is_symlink() {
                    return Ok(true);
                }
            }
        }
    }
    Ok(false)
}

/// The most links [`NodeModules::resolve`] follows for one entry, like the operating systems' own limit.
const MAX_HOPS: usize = 40;

/// Where a link of the project's `node_modules` leads (see [`NodeModules::resolve`]).
enum Resolved {
    /// To this real path inside the project, relative to it, reached without any link.
    Inside { relative: PathBuf, is_dir: bool },
    /// Out of the project, not followed further.
    Outside,
    /// Nowhere usable: a broken link, too many links, or a target with a network or device prefix.
    LeftOut,
}

/// The folders of the tree the copy holds (`""` for the root), sorted, and the paths of the tree's files and
/// folders named `node_modules` (see [`key`]).
fn tree_dirs(copy: &TestCopy) -> io::Result<(Vec<String>, HashSet<String>)> {
    let files = copy
        .tree_files()
        .ok_or_else(|| io::Error::other("the test copy holds no step yet"))?;
    let mut dirs = HashSet::from([""]);
    let mut taken = HashSet::new();
    for file in files {
        if is_node_modules(name(file)) {
            taken.insert(key(file));
        }
        let mut path = file;
        while let Some((parent, _)) = path.rsplit_once('/') {
            // Its parents were added with it.
            if !dirs.insert(parent) {
                break;
            }
            if is_node_modules(name(parent)) {
                taken.insert(key(parent));
            }
            path = parent;
        }
    }
    let mut dirs: Vec<String> = dirs.into_iter().map(str::to_owned).collect();
    dirs.sort_unstable();
    Ok((dirs, taken))
}

/// The last component of a `/`-separated path.
fn name(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

/// Whether `name` is `node_modules`, whatever its case: even on a case-sensitive file system, a folder may
/// ignore case (ext4 `casefold`), so a tree's `Node_Modules` is never taken for a farm's place.
fn is_node_modules(name: &str) -> bool {
    name.eq_ignore_ascii_case(NODE_MODULES)
}

/// `path` in the form that tells whether two paths of the tree may be the same file (see
/// [`is_node_modules`]).
fn key(path: &str) -> String {
    path.to_lowercase()
}

/// Whether the entry name `name` is one of `names`, without regard to case where the file system ignores it.
fn is_one_of(name: &OsStr, names: &[&str]) -> bool {
    name.to_str().is_some_and(|name| {
        names.iter().any(|other| {
            if CASE_INSENSITIVE {
                name.eq_ignore_ascii_case(other)
            } else {
                name == *other
            }
        })
    })
}

/// Removes the farm `farm` of the copy at `root` and the folders this leaves empty, up to the first folder of
/// the tree (`tree_dirs`). Returns whether there was something to remove. Nothing is removed through a link:
/// if a folder above the farm is not a real folder, the farm is not there.
fn remove_farm(root: &Path, farm: &str, tree_dirs: &HashSet<&str>) -> io::Result<bool> {
    if !parents(farm).all(|parent| is_real_dir_no_follow(&native(root, parent))) {
        return Ok(false);
    }
    let full = native(root, farm);
    match fs::symlink_metadata(&full) {
        Ok(metadata) => remove_entry(&full, &metadata)?,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(false),
        Err(error) => return Err(error),
    }
    let mut path = farm;
    while let Some((parent, _)) = path.rsplit_once('/') {
        // Stops at the first folder that still holds something.
        if tree_dirs.contains(parent) || fs::remove_dir(native(root, parent)).is_err() {
            break;
        }
        path = parent;
    }
    Ok(true)
}

/// Makes `dir`, a farm or a scope folder in one inside the copy at `root`, a real folder holding `wants`.
/// `made_link`: see [`link_to`].
fn sync(
    root: &Path,
    dir: &Path,
    wants: &[(OsString, Want)],
    linked: &mut Linked,
    made_link: &mut bool,
) -> io::Result<()> {
    match fs::symlink_metadata(dir) {
        Ok(metadata) if metadata.is_dir() => make_owner_writable(dir, &metadata)?,
        Ok(metadata) => {
            remove_entry(dir, &metadata)?;
            linked.removed += 1;
            fs::create_dir(dir)?;
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => fs::create_dir(dir)?,
        Err(error) => return Err(error),
    }

    let wanted: HashSet<&OsStr> = wants.iter().map(|(name, _)| name.as_os_str()).collect();
    // Which entries are links, from the listing: checking a farm of a few hundred links then costs one
    // `read_link` each.
    let mut links = HashSet::new();
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        // The type of the entry itself: a link is not followed.
        let file_type = entry.file_type()?;
        let name = entry.file_name();
        let created_by_run = file_type.is_dir() || file_type.is_file();
        if wanted.contains(name.as_os_str()) {
            if file_type.is_symlink() {
                links.insert(name);
            }
        } else if !created_by_run {
            let path = entry.path();
            remove_entry(&path, &fs::symlink_metadata(&path)?)?;
            linked.removed += 1;
        }
    }

    for (name, want) in wants {
        let path = dir.join(name);
        let is_link = links.contains(name);
        match want {
            Want::Link(target) => {
                if link_to(&path, is_link, target, made_link)? {
                    linked.links += 1;
                }
            }
            Want::Workspace(relative) => {
                if is_real_dir_below(root, relative) {
                    if link_to(&path, is_link, &root.join(relative), made_link)? {
                        linked.links += 1;
                    }
                } else if let Ok(metadata) = fs::symlink_metadata(&path) {
                    remove_entry(&path, &metadata)?;
                    linked.removed += 1;
                }
            }
            Want::File(bytes) => {
                if !holds_file(&path, bytes)? {
                    write_file(&path, FileKind::Regular, bytes)?;
                    linked.files += 1;
                }
            }
            Want::Dir(scope) => sync(root, &path, scope, linked, made_link)?,
        }
    }
    Ok(())
}

/// Whether `relative` is a real folder under `root`, reached through real folders.
fn is_real_dir_below(root: &Path, relative: &Path) -> bool {
    let mut path = root.to_owned();
    relative.components().all(|component| {
        path.push(component);
        is_real_dir_no_follow(&path)
    })
}

/// Whether `path` is a regular file as the copy writes it (not a link, see [`is_written_as`]) holding
/// `bytes`.
fn holds_file(path: &Path, bytes: &[u8]) -> io::Result<bool> {
    let metadata = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(false),
        Err(error) => return Err(error),
    };
    Ok(is_written_as(&metadata, FileKind::Regular)
        && metadata.len() == bytes.len() as u64
        && safe_fs::read_small_regular_file(path, MAX_COPIED_FILE_BYTES).as_deref() == Some(bytes))
}

